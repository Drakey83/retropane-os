/// Packed glyphs: bit (4 - x) of `GLYPHS[c][y]` is pixel (x, y).
pub const GLYPHS: [[u8; HEIGHT]; 95] = pack();

const fn pack() -> [[u8; HEIGHT]; 95] {
    let mut out = [[0u8; HEIGHT]; 95];
    let mut g = 0;
    while g < 95 {
        let mut y = 0;
        while y < HEIGHT {
            let row = SRC[g][y].as_bytes();
            assert!(row.len() == WIDTH, "glyph rows must be 5 wide");
            let mut bits = 0u8;
            let mut x = 0;
            while x < WIDTH {
                if row[x] == b'#' {
                    bits |= 1 << (WIDTH - 1 - x);
                }
                x += 1;
            }
            out[g][y] = bits;
            y += 1;
        }
        g += 1;
    }
    out
}

/// The rows of `c`'s glyph; anything outside printable ASCII draws as `?`.
#[must_use]
pub fn glyph(c: char) -> &'static [u8; HEIGHT] {
    let i = match c {
        ' '..='~' => c as usize - 0x20,
        _ => '?' as usize - 0x20,
    };
    &GLYPHS[i]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn packs_bits_left_to_right() {
        assert_eq!(glyph('A')[0], 0b01110);
        assert_eq!(glyph('A')[3], 0b11111);
        assert_eq!(glyph(' '), &[0; HEIGHT]);
        assert_eq!(glyph('\u{1F600}'), glyph('?'));
    }

    #[test]
    fn every_printable_glyph_except_space_has_ink() {
        for c in '!'..='~' {
            assert!(glyph(c).iter().any(|&r| r != 0), "{c:?} is blank");
        }
    }

    #[test]
    fn letters_are_distinct() {
        for a in 'A'..='z' {
            for b in 'A'..='z' {
                if a != b && a.is_ascii_alphanumeric() && b.is_ascii_alphanumeric() {
                    assert_ne!(glyph(a), glyph(b), "{a} and {b} look the same");
                }
            }
        }
    }
}
