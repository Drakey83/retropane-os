#include "common.h"
#include "library.h"
#include "platform/platform.h"
#include <retropane.h>

/*
The engine loads its parts by name: the file system, a renderer, the menu,
and the game's own logic (the client and server libraries of the
Half-Life SDK). How RetroPane does it is ADR-0039:

- The file system, the renderer and the menu are the engine's own (GPL)
  and are linked into the engine's module. Their entry points were renamed
  by the build so the parts' names do not clash, and the build generates
  the table below from what each part's source marks for export
  (xtask/src/xash.rs): a load of one of them is a look in that table, and
  nothing is read from the card.
- The game's logic must stay libraries of their own, loaded at run time and
  never linked into the engine (Valve's SDK terms and the GPL do not
  combine: docs/research/half-life-licences.md). Each is a module file the
  runner's loader puts in place (rp_module_load): linked by the build at
  the address it runs at, so there is no relocation and no call table, and
  refused with a plain reason if it was built for another runner or is
  damaged. Its names are two tables the build sorted: a name's function
  (every entity class of a map is looked up so) and a function's name
  (saved games store functions by name) are each a binary search.

The engine asks by plain names here (XASH_INTERNAL_GAMELIBS: "server",
"client", "menu", "ref_soft", "filesystem_stdio"); a module's file is
that name with ".rpm".
*/

typedef struct
{
	const char *name;
	void       *function;
} rp_inner_export_t;

typedef struct
{
	const char              *name;	// what the engine asks for; NULL ends the table
	const rp_inner_export_t *exports;
	unsigned                 count;
} rp_inner_library_t;

// generated by the build with the engine's module
extern const rp_inner_library_t rp_inner_libraries[];

static const rp_inner_library_t *RP_InnerLibrary( void *hInstance )
{
	const rp_inner_library_t *lib;

	for( lib = rp_inner_libraries; lib->name; lib++ )
	{
		if( (void *)lib == hInstance )
			return lib;
	}
	return NULL;
}

void *COM_LoadLibrary( const char *dllname, int build_ordinals_table, qboolean directpath )
{
	const rp_inner_library_t *lib;
	char  base[48], file[64];
	void *module;

	COM_ResetLibraryError();
	if( COM_StringEmptyOrNULL( dllname ))
		return NULL;

	COM_FileBase( dllname, base, sizeof( base ));
	for( lib = rp_inner_libraries; lib->name; lib++ )
	{
		if( !Q_stricmp( base, lib->name ))
			return (void *)lib;
	}

	Q_snprintf( file, sizeof( file ), "%s.rpm", base );
	module = rp_module_load( file );
	if( !module )
	{
		char why[160];

		Q_snprintf( why, sizeof( why ), "%s: %s", file, rp_module_error());
		COM_PushLibraryError( why );
		return NULL;
	}
	return module;
}

void COM_FreeLibrary( void *hInstance )
{
	if( hInstance && !RP_InnerLibrary( hInstance ))
		rp_module_free( hInstance );
}

void *COM_GetProcAddress( void *hInstance, const char *name )
{
	const rp_inner_library_t *lib;
	unsigned i;

	if( !hInstance || !name )
		return NULL;

	lib = RP_InnerLibrary( hInstance );
	if( !lib )
		return rp_module_find( hInstance, name );

	// a handful of names a part: no table worth sorting
	for( i = 0; i < lib->count; i++ )
	{
		if( !Q_strcmp( lib->exports[i].name, name ))
			return lib->exports[i].function;
	}
	return NULL;
}

void *COM_FunctionFromName( void *hInstance, const char *pName )
{
	return COM_GetProcAddress( hInstance, pName );
}

const char *COM_NameForFunction( void *hInstance, void *function )
{
	const rp_inner_library_t *lib;
	unsigned i;

	if( !hInstance || !function )
		return NULL;

	lib = RP_InnerLibrary( hInstance );
	if( !lib )
		return rp_module_name( hInstance, function );

	for( i = 0; i < lib->count; i++ )
	{
		if( lib->exports[i].function == function )
			return lib->exports[i].name;
	}
	return NULL;
}
