"""Renders the shell's fonts into Rust glyph tables (ADR-0021).

    python -I tools/shell-assets/fonts.py <DidactGothic-Regular.ttf> <out.rs>

The font is Didact Gothic (SIL Open Font License 1.1; its licence text is
committed next to the output, as the OFL requires). Each size becomes an
`rp_draw::Font`: 8-bit coverage masks from FreeType's anti-aliasing (via
Pillow), placed on the baseline. The output is deterministic, so it is
committed and regenerated only when sizes change; the TTF's SHA-256 is
recorded in it.

Run with `-I` (isolated): the TTF is downloaded data.
"""

import hashlib
import sys

from PIL import Image, ImageDraw, ImageFont

# name, pixel size, first..last character, extra tracking (spaced capitals
# for labels), characters actually drawn (others are empty entries).
SIZES = [
    # 0x7F draws the degree sign (DEL has no other use) and 0x80 the middle
    # dot (a separator, " · "): the small fonts have no room for the whole
    # Latin-1 range, and the shell needs only these two extras.
    ("UI", 18, 0x20, 0x80, 0, None),
    ("LABEL", 15, 0x20, 0x80, 2, None),
    ("BIG", 76, 0x30, 0xB0, 0, "0123456789:°"),
]


def glyph(font, ch, tracking):
    ascent, descent = font.getmetrics()
    pad = 8
    size = (font.size * 2 + pad * 2, ascent + descent + pad * 2)
    img = Image.new("L", size, 0)
    base = pad + ascent
    ImageDraw.Draw(img).text((pad, base), ch, font=font, fill=255, anchor="ls")
    advance = round(font.getlength(ch)) + tracking
    box = img.getbbox()
    if box is None:
        return (0, 0, 0, 0, advance, b"")
    x0, y0, x1, y1 = box
    mask = img.crop(box).tobytes()
    return (x1 - x0, y1 - y0, x0 - pad, base - y0, advance, mask)


def main():
    ttf, out = sys.argv[1], sys.argv[2]
    data = open(ttf, "rb").read()
    digest = hashlib.sha256(data).hexdigest()
    lines = [
        "//! Generated by `tools/shell-assets/fonts.py` from Didact Gothic",
        "//! (SIL Open Font License 1.1: `OFL-DidactGothic.txt` in this crate),",
        f"//! `DidactGothic-Regular.ttf` SHA-256 {digest}. Do not edit.",
        "",
        "use rp_draw::{Font, Glyph};",
        "",
        "const fn g(w: u8, h: u8, left: i8, top: i8, advance: u8, cover: &'static [u8]) -> Glyph {",
        "    Glyph { w, h, left, top, advance, cover }",
        "}",
        "",
    ]
    total = 0
    for name, px, first, last, tracking, only in SIZES:
        font = ImageFont.truetype(ttf, px)
        ascent, descent = font.getmetrics()
        entries = []
        for code in range(first, last + 1):
            ch = {0x7F: "°", 0x80: "·"}.get(code, chr(code))
            if only is not None and ch not in only:
                entries.append("    g(0, 0, 0, 0, 0, &[]),")
                continue
            w, h, left, top, advance, mask = glyph(font, ch, tracking)
            assert w < 256 and h < 256 and -128 <= left < 128 and -128 <= top < 128 and advance < 256
            total += len(mask)
            body = ",".join(str(b) for b in mask)
            entries.append(f"    g({w}, {h}, {left}, {top}, {advance}, &[{body}]),")
        n = last - first + 1
        lines.append(f"/// Didact Gothic {px} px" + (f", tracking +{tracking}" if tracking else "") + ".")
        lines.append(f"pub static {name}: Font = Font {{ line: {ascent + descent}, ascent: {ascent}, first: {first}, glyphs: &{name}_GLYPHS }};")
        lines.append(f"static {name}_GLYPHS: [Glyph; {n}] = [")
        lines.extend(entries)
        lines.append("];")
        lines.append("")
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{out}: {total} bytes of coverage")


if __name__ == "__main__":
    main()
