"""Turns the default weather icons into Rust data for the Today test image (ADR-0021).

    python -I tools/shell-assets/icons.py <assets/weather/vclouds> <out.rs> [--all]

`--all` makes the SD card's pack (`local/icons/icons-all.rs`, every condition
at every size); without it, the sample's pictures the image carries.

The Today screen shows one big icon and small ones, as in the mock-ups
(docs/design/mockups): each picture is cropped to what is drawn in it (its
visible part plus a 3% margin), then scaled uniformly, never stretched, to the
largest size that fits its box: 250 x 176 for the big one, 66 x 66 for the
small ones. The shell centres the result in the box. This is the only resizing,
done here with a good filter so the device never scales. Pixels are straight
(non-premultiplied) ARGB8888, which is what `rp_draw::Image` draws. The output
goes in `local/`, never committed (the test image builds without it, with
empty pictures); the icons themselves are committed under `assets/` with their
credit.

Run with `-I` (isolated): the pictures are data from elsewhere.
"""

import sys

from PIL import Image

# The pictures the screens show: the big one for the reading now, and every
# icon the sample forecast uses (shell/weather's SAMPLE_ICONS, read from the
# source below so the two can't drift) at two sizes: the forecast cards'
# (66 px) and the Weather app's rows (40 px). Only those, not all 22: the lean
# rule; the OS's packs go through the icon atlas instead (docs/design/icons.md).
HERO = "03"
BIG = (250, 176)
CARD = (66, 66)
ROW = (40, 40)


def sample_icons():
    import pathlib
    import re
    src = (pathlib.Path(__file__).resolve().parents[2] / "shell/weather/src/lib.rs").read_text(encoding="utf-8")
    def ids(name):
        m = re.search(name + r": \[u8; \d+\] = \[([0-9, ]+)\]", src)
        return [int(x) for x in m.group(1).split(",")]
    return ids("SAMPLE_CARD_ICONS"), ids("SAMPLE_ICONS")


def subject(img):
    """The picture cropped to its visible part plus a 3% margin."""
    box = img.getchannel("A").point(lambda a: 255 if a > 8 else 0).getbbox()
    x0, y0, x1, y1 = box
    m = int(max(x1 - x0, y1 - y0) * 0.03)
    return img.crop((max(0, x0 - m), max(0, y0 - m), min(img.width, x1 + m), min(img.height, y1 + m)))


def fit(img, size):
    """Scaled uniformly to the largest size inside `size`."""
    k = min(size[0] / img.width, size[1] / img.height)
    return img.resize((max(1, round(img.width * k)), max(1, round(img.height * k))), Image.LANCZOS)


def words(img):
    raw = img.convert("RGBA").tobytes()
    return ",".join(
        f"0x{raw[i + 3]:02X}{raw[i]:02X}{raw[i + 1]:02X}{raw[i + 2]:02X}"
        for i in range(0, len(raw), 4)
    )


def main():
    folder, out = sys.argv[1], sys.argv[2]

    def load(name):
        return subject(Image.open(f"{folder}/{name}.png").convert("RGBA"))

    # Each picture run-length packed (R129, the lean rule: the test image
    # had to fit the loader's image area): a header word, zeros << 16 |
    # solid, written in decimal so the build's look (shell/today/build.rs)
    # leaves it alone, then the solid pixels in hex. The image unpacks them
    # once at start into RAM outside the image area.
    def packed(img):
        raw = img.convert("RGBA").tobytes()
        px = [(raw[i + 3] << 24) | (raw[i] << 16) | (raw[i + 1] << 8) | raw[i + 2] for i in range(0, len(raw), 4)]
        out, i = [], 0
        while i < len(px):
            z = 0
            while i < len(px) and px[i] >> 24 == 0 and z < 0xFFFF:
                z += 1
                i += 1
            lits = []
            while i < len(px) and px[i] >> 24 != 0 and len(lits) < 0xFFFF:
                lits.append(px[i])
                i += 1
            out.append(str((z << 16) | len(lits)))
            out += [f"0x{p:08X}" for p in lits]
        return out

    # `--all`: every condition at every size, for the pack on the SD card
    # (real forecasts use any of the 22: the owner's run, 2026-10-31, fog
    # had no picture); else the sample's, built into the image as the
    # fallback when the card has no pack.
    if "--all" in sys.argv:
        ids = range(1, 23)
        items = [(0, i, fit(load(f"{i:02}"), BIG)) for i in ids]
        items += [(1, i, fit(load(f"{i:02}"), CARD)) for i in ids]
        items += [(2, i, fit(load(f"{i:02}"), ROW)) for i in ids]
    else:
        cards, rows = sample_icons()
        items = [(0, int(HERO), fit(load(HERO), BIG))]
        items += [(1, i, fit(load(f"{i:02}"), CARD)) for i in cards]
        items += [(2, i, fit(load(f"{i:02}"), ROW)) for i in rows]
    lines = ["// Generated by tools/shell-assets/icons.py. Do not edit.", ""]
    table, words, names = [], 0, []
    for k, (kind, i, img) in enumerate(items):
        p = packed(img)
        lines.append(f"static P{k}: [u32; {len(p)}] = [{','.join(p)}];")
        table.append(f"({kind}, {i}, {img.width}, {img.height}, &P{k})")
        words += img.width * img.height
        names.append(f"{('hero', 'card', 'row')[kind]} {i:02} {img.width}x{img.height}")
    lines.append(f"pub const COUNT: usize = {len(items)};")
    lines.append(f"pub const WORDS: usize = {words};")
    lines.append(f"/// (0 hero, 1 card, 2 row; pack id; width; height; packed pixels)")
    lines.append(f"pub static PACKED: [(u8, u8, u16, u16, &[u32]); COUNT] = [{', '.join(table)}];")
    open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"{out}: " + ", ".join(names))


main()
