"""Turns the default weather icons into Rust data for the Today test image (ADR-0021).

    python -I tools/shell-assets/icons.py <assets/weather/vclouds> <out.rs>

The Today screen shows one big icon and five small ones. The big one is the
picture at its own size (VClouds' icons are 175 x 120); the small ones are the
same pictures scaled by exactly one third (58 x 40), the only resizing, done
here with a good filter so the device never scales. Pixels are straight
(non-premultiplied) ARGB8888, which is what `rp_draw::Image` draws. The output
goes in `local/`, never committed (the test image builds without it, with
empty pictures); the icons themselves are committed under `assets/` with their
credit.

Run with `-I` (isolated): the pictures are data from elsewhere.
"""

import sys

from PIL import Image

# The pictures the sample Today screen shows: the hero, then the forecast row
# (their order is the order of the sample data in shell/core: partly cloudy
# now; then light rain, cloudy, rain showers, clear and partly cloudy).
HERO = "03"
FORECAST = ["09", "05", "12", "01", "03"]
SMALL = (58, 40)


def words(img):
    raw = img.convert("RGBA").tobytes()
    return ",".join(
        f"0x{raw[i + 3]:02X}{raw[i]:02X}{raw[i + 1]:02X}{raw[i + 2]:02X}"
        for i in range(0, len(raw), 4)
    )


def main():
    folder, out = sys.argv[1], sys.argv[2]

    def load(name):
        return Image.open(f"{folder}/{name}.png").convert("RGBA")

    hero = load(HERO)
    assert hero.size == (175, 120), hero.size
    lines = [
        "// Generated by tools/shell-assets/icons.py. Do not edit.",
        "",
        f"pub static HERO_PX: [u32; {hero.width * hero.height}] = [{words(hero)}];",
        f"pub static HERO: Image = Image {{ w: {hero.width}, h: {hero.height}, px: &HERO_PX }};",
    ]
    names = []
    for i, name in enumerate(FORECAST):
        small = load(name).resize(SMALL, Image.LANCZOS)
        lines.append(
            f"static SMALL_PX_{i}: [u32; {SMALL[0] * SMALL[1]}] = [{words(small)}];"
        )
        names.append(
            f"Image {{ w: {SMALL[0]}, h: {SMALL[1]}, px: &SMALL_PX_{i} }}"
        )
    lines.append(f"pub static SMALL: [Image; {len(FORECAST)}] = [{', '.join(names)}];")
    open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"{out}: {hero.width}x{hero.height} hero and {len(FORECAST)} icons of {SMALL[0]}x{SMALL[1]}")


main()
